# 1. Primitive helpers
# =============================================================================

# Draw a stationary AR(1) path.  The pre-sample state is drawn from the
# invariant distribution N(0, 1/(1 - phi^2)), so x[1] is already stationary and
# no burn-in is needed.
draw_ar1 <- function(n, phi) {
  as.vector(stats::filter(
    rnorm(n), phi, method = "recursive",
    init = rnorm(1, sd = 1 / sqrt(1 - phi^2))
  ))
}

# Draw an invertible MA(2) path: z_t = e_t + theta1 e_{t-1} + theta2 e_{t-2}.
# An MA process is stationary from the first observation, so the two leading
# NAs from the convolution filter are simply discarded.
draw_ma2 <- function(n, theta1, theta2) {
  e <- rnorm(n + 2)
  z <- stats::filter(e, c(1, theta1, theta2), method = "convolution", sides = 1)
  as.vector(z)[-(1:2)]
}

# Autocorrelations of the MA(2) above.
ma2_acf <- function(theta1, theta2, k) {
  den <- 1 + theta1^2 + theta2^2
  ifelse(k == 0, 1,
  ifelse(abs(k) == 1, (theta1 + theta1 * theta2) / den,
  ifelse(abs(k) == 2, theta2 / den, 0)))
}

# Bandwidth rule for the Bartlett kernel.  L ~ T^(1/3) is the MSE-optimal rate
# for the Bartlett kernel and satisfies L -> Inf, L/T -> 0.  It is deliberately
# more generous than the Newey-West rule of thumb 4 (T/100)^(2/9), because the
# scores generated by persistent AR(1) pairs have a long autocovariance tail.
hac_bandwidth <- function(n) floor(2 * n^(1 / 3))

# --- Bartlett long-run variance, scalar and matrix versions ------------------
# Both apply the same n/(n - k) degrees-of-freedom adjustment, where k is the
# number of estimated regression coefficients, so that every HAC number
# reported in the handout comes from one estimator.

hac_lrv <- function(score, L, dof_scale = 1) {
  n <- length(score)
  v <- sum(score^2) / n
  if (L > 0) {
    for (lag in seq_len(L)) {
      g <- sum(score[(lag + 1):n] * score[1:(n - lag)]) / n
      v <- v + 2 * (1 - lag / (L + 1)) * g
    }
  }
  v * dof_scale
}

hac_lrv_matrix <- function(S, L, dof_scale = 1) {
  n <- nrow(S)
  Omega <- crossprod(S) / n
  if (L > 0) {
    for (lag in seq_len(L)) {
      G <- crossprod(S[(lag + 1):n, , drop = FALSE],
                     S[1:(n - lag), , drop = FALSE]) / n
      Omega <- Omega + (1 - lag / (L + 1)) * (G + t(G))
    }
  }
  Omega * dof_scale
}

# Jarque-Bera normality statistic and its asymptotic chi-squared(2) p-value,
# implemented directly (rather than importing tseries) for the same reason the
# HAC estimator above is implemented directly: a single, auditable formula
# used everywhere in the handout.
jarque_bera <- function(x) {
  n    <- length(x)
  m    <- mean(x)
  v    <- mean((x - m)^2)
  skew <- mean((x - m)^3) / v^1.5
  kurt <- mean((x - m)^4) / v^2
  stat <- n / 6 * (skew^2 + (kurt - 3)^2 / 4)
  c(statistic = stat, p_value = 1 - pchisq(stat, df = 2))
}

# =============================================================================
# 2. Test statistics for the simple regression y ~ 1 + x
# =============================================================================

# Returns the conventional, HC0 and Bartlett-HAC t-ratios for the slope.
slope_t_stats <- function(x, y) {
  n  <- length(x)
  xc <- x - mean(x)
  yc <- y - mean(y)
  sxx <- sum(xc^2)
  b   <- sum(xc * yc) / sxx
  resid <- yc - b * xc
  score <- xc * resid

  dof <- n / (n - 2)
  se_conventional <- sqrt(sum(resid^2) / (n - 2) / sxx)
  se_hc0 <- sqrt(sum(score^2) * dof / sxx^2)
  se_hac <- sqrt(n * hac_lrv(score, hac_bandwidth(n), dof) / sxx^2)

  c(`Conventional OLS` = b / se_conventional,
    HC0 = b / se_hc0,
    HAC = b / se_hac)
}

# Rejection indicators at level alpha.  The conventional statistic is compared
# with the Student-t critical value it would have under exact Gaussian
# conditions; the robust statistics have N(0,1) limits, and the t critical
# value is used for them only as a mild finite-sample concession.  The
# difference is negligible at the sample sizes considered here.
slope_rejections <- function(x, y, alpha) {
  abs(slope_t_stats(x, y)) > qt(1 - alpha / 2, length(x) - 2)
}

# =============================================================================
# 3. DGP registry
#
# Each entry supplies a draw() returning a list(x, y) of length n, together
# with the theoretical variance ratio lambda implied by the theory section.
# Storing lambda per DGP (rather than deriving it from an AR(1) formula) lets
# the registry hold non-AR(1) designs.
# =============================================================================

ar_pair <- function(phi_x, phi_y) {
  force(phi_x); force(phi_y)
  function(n) list(x = draw_ar1(n, phi_x), y = draw_ar1(n, phi_y))
}

lambda_ar_pair <- function(phi_x, phi_y) {
  r <- phi_x * phi_y
  (1 + r) / (1 - r)
}

# --- the lambda = 1 design ---------------------------------------------------
# x is AR(1) with coefficient phi; y is an invertible MA(2).  Choosing
#     theta1 = -phi * theta2 / (1 + theta2)
# forces  sum_k rho_x(k) rho_y(k) = 1  exactly, so the conventional test is
# correctly sized even though BOTH series are visibly serially correlated.
# This is the counterexample to "serial correlation implies size distortion".
lambda1_phi    <- 0.5
lambda1_theta2 <- 0.5
lambda1_theta1 <- -lambda1_phi * lambda1_theta2 / (1 + lambda1_theta2)

lambda_ar_ma2 <- function(phi, theta1, theta2) {
  1 + 2 * sum(phi^(1:2) * ma2_acf(theta1, theta2, 1:2))
}

dgp_registry <- list(
  list(dgp = "iid", type = "stationary", lambda = 1,
       draw = function(n) list(x = rnorm(n), y = rnorm(n))),
  list(dgp = "(0.5,0.5)", type = "stationary", lambda = lambda_ar_pair(0.5, 0.5),
       draw = ar_pair(0.5, 0.5)),
  list(dgp = "(0.8,0.8)", type = "stationary", lambda = lambda_ar_pair(0.8, 0.8),
       draw = ar_pair(0.8, 0.8)),
  list(dgp = "(0.9,0.9)", type = "stationary", lambda = lambda_ar_pair(0.9, 0.9),
       draw = ar_pair(0.9, 0.9)),
  list(dgp = "(0.95,0.95)", type = "stationary", lambda = lambda_ar_pair(0.95, 0.95),
       draw = ar_pair(0.95, 0.95)),
  list(dgp = "(0.9,0.5)", type = "stationary", lambda = lambda_ar_pair(0.9, 0.5),
       draw = ar_pair(0.9, 0.5)),
  list(dgp = "(0.8,-0.8)", type = "stationary", lambda = lambda_ar_pair(0.8, -0.8),
       draw = ar_pair(0.8, -0.8)),
  list(dgp = "AR/MA lambda=1", type = "stationary",
       lambda = lambda_ar_ma2(lambda1_phi, lambda1_theta1, lambda1_theta2),
       draw = function(n) list(
         x = draw_ar1(n, lambda1_phi),
         y = draw_ma2(n, lambda1_theta1, lambda1_theta2))),
  list(dgp = "I(1)", type = "integrated", lambda = NA_real_,
       draw = function(n) list(x = cumsum(rnorm(n)), y = cumsum(rnorm(n))))
)

dgp_levels <- vapply(dgp_registry, `[[`, character(1), "dgp")

dgp_spec <- data.frame(
  dgp    = dgp_levels,
  type   = vapply(dgp_registry, `[[`, character(1), "type"),
  lambda = vapply(dgp_registry, `[[`, numeric(1), "lambda"),
  stringsAsFactors = FALSE
)
dgp_spec$asymptotic <- ifelse(
  is.na(dgp_spec$lambda), NA_real_,
  2 * pnorm(-qnorm(1 - alpha / 2) / sqrt(dgp_spec$lambda))
)

stationary_spec <- subset(dgp_spec, type == "stationary")

# =============================================================================
# 4. Main experiment
#
# One trajectory of length Tmax per replication.  The conventional statistic is
# evaluated on every nested prefix via cumulative sums; the HAC statistic, which
# cannot be updated recursively, is evaluated at selected_T only.
# =============================================================================

simulate_dgp <- function(entry, Tmax, grid, selected_T, Nsim, alpha) {
  conventional_rej <- matrix(FALSE, nrow = length(grid),       ncol = Nsim)
  hac_rej          <- matrix(FALSE, nrow = length(selected_T), ncol = Nsim)

  # t-statistics at selected_T only, kept purely for the Jarque-Bera check
  # below: the shape of the limiting distribution, as opposed to the
  # rejection frequencies above, which check its tail mass.
  conventional_t <- matrix(NA_real_, nrow = length(selected_T), ncol = Nsim)
  hac_t          <- matrix(NA_real_, nrow = length(selected_T), ncol = Nsim)
  sel_idx        <- match(selected_T, grid)

  for (r in seq_len(Nsim)) {
    d <- entry$draw(Tmax)
    x <- d$x
    y <- d$y

    # --- conventional statistic on every prefix, via running sums ----------
    cs <- cbind(cumsum(x), cumsum(y), cumsum(x^2), cumsum(y^2), cumsum(x * y))
    nn   <- grid
    Sx   <- cs[nn, 1]; Sy <- cs[nn, 2]
    Sxx  <- cs[nn, 3]; Syy <- cs[nn, 4]; Sxy <- cs[nn, 5]
    Sxxc <- Sxx - Sx^2 / nn
    Sxyc <- Sxy - Sx * Sy / nn
    Syyc <- Syy - Sy^2 / nn
    b    <- Sxyc / Sxxc
    ssr  <- Syyc - b * Sxyc
    se   <- sqrt((ssr / (nn - 2)) / Sxxc)
    tstat <- b / se
    conventional_rej[, r] <- abs(tstat) > qt(1 - alpha / 2, nn - 2)
    conventional_t[, r]   <- tstat[sel_idx]

    # --- HAC statistic at selected sample sizes ---------------------------
    for (j in seq_along(selected_T)) {
      n <- selected_T[j]
      stats <- slope_t_stats(x[seq_len(n)], y[seq_len(n)])
      hac_t[j, r]   <- stats[["HAC"]]
      hac_rej[j, r] <- abs(stats[["HAC"]]) > qt(1 - alpha / 2, n - 2)
    }
  }

  jb_conventional <- apply(conventional_t, 1, jarque_bera)
  jb_hac          <- apply(hac_t,          1, jarque_bera)

  list(
    conventional = data.frame(T = grid, reject = rowMeans(conventional_rej),
                              method = "Conventional OLS", dgp = entry$dgp,
                              Nsim = Nsim, stringsAsFactors = FALSE),
    hac = data.frame(T = selected_T, reject = rowMeans(hac_rej),
                     method = "HAC", dgp = entry$dgp,
                     Nsim = Nsim, stringsAsFactors = FALSE),
    normality = data.frame(
      T = rep(selected_T, 2),
      method = rep(c("Conventional OLS", "HAC"), each = length(selected_T)),
      jb_statistic = c(jb_conventional["statistic", ], jb_hac["statistic", ]),
      jb_pvalue    = c(jb_conventional["p_value", ],   jb_hac["p_value", ]),
      dgp = entry$dgp, Nsim = Nsim, stringsAsFactors = FALSE)
  )
}

