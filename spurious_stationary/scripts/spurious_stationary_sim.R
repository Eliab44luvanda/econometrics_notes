# =============================================================================
# 9. Accessors used by the handout
#
# The handout quotes no hard-coded numbers: every figure in the prose is pulled
# from these accessors at render time.  Each one fails loudly rather than
# returning a wrong or empty value, so a mismatch between the text and the
# simulation cannot pass silently.
# =============================================================================

.one <- function(v, what) {
  v <- v[!is.na(v)]
  if (length(v) != 1L)
    stop(sprintf("accessor '%s' matched %d records, expected 1", what, length(v)))
  v
}

pc <- function(p, digits = 1) sprintf(paste0("%.", digits, "f%%"), 100 * p)

# main experiment
rej_of <- function(dgp_name, n, method = "Conventional OLS") {
  src <- if (identical(method, "HAC")) hac_res else res
  .one(src$reject[as.character(src$dgp) == dgp_name & src$T == n],
       sprintf("rej_of(%s, %d, %s)", dgp_name, n, method))
}
rp <- function(dgp_name, n, method = "Conventional OLS", digits = 1)
  pc(rej_of(dgp_name, n, method), digits)

dgp_jb <- function(dgp_name, n, method = "Conventional OLS",
                   what = c("jb_statistic", "jb_pvalue"), digits = 2) {
  what <- match.arg(what)
  sprintf(paste0("%.", digits, "f"),
          .one(dgp_normality_res[[what]][as.character(dgp_normality_res$dgp) == dgp_name &
                                         dgp_normality_res$T == n &
                                         dgp_normality_res$method == method],
               sprintf("dgp_jb(%s, %d, %s, %s)", dgp_name, n, method, what)))
}

lambda_of <- function(dgp_name)
  .one(dgp_spec$lambda[dgp_spec$dgp == dgp_name], sprintf("lambda_of(%s)", dgp_name))
asy_of <- function(dgp_name, digits = 1)
  pc(.one(dgp_spec$asymptotic[dgp_spec$dgp == dgp_name],
          sprintf("asy_of(%s)", dgp_name)), digits)

