# =============================================================================
# 5. Extension 1: dependent series with a zero projection slope
#
# x and y share a persistent stochastic scale but have independent signs, so
# Cov(x, y) = 0 while the series are dependent.  The score is exactly serially
# uncorrelated, yet lambda = E(s^4) / E(s^2)^2 = exp(v_h) > 1: the distortion is
# entirely contemporaneous.  HC is sufficient here; HAC is valid but noisier.
# =============================================================================

simulate_common_volatility <- function(Tmax, selected_T, Nsim, alpha,
                                       volatility_rho = 0.95,
                                       volatility_variance = 0.5) {
  methods <- c("Conventional OLS", "HC0", "HAC")
  out <- array(FALSE, dim = c(length(selected_T), length(methods), Nsim),
               dimnames = list(NULL, methods, NULL))
  innovation_sd <- sqrt(volatility_variance * (1 - volatility_rho^2))

  for (r in seq_len(Nsim)) {
    h <- as.vector(stats::filter(
      rnorm(Tmax, sd = innovation_sd), volatility_rho,
      method = "recursive", init = rnorm(1, sd = sqrt(volatility_variance))
    ))
    s <- exp(h / 2)
    x <- s * rnorm(Tmax)
    y <- s * rnorm(Tmax)
    for (j in seq_along(selected_T)) {
      n <- selected_T[j]
      out[j, , r] <- slope_rejections(x[seq_len(n)], y[seq_len(n)], alpha)[methods]
    }
  }

  do.call(rbind, lapply(seq_along(selected_T), function(j) {
    data.frame(T = selected_T[j], method = methods,
               reject = as.numeric(rowMeans(out[j, , ])),
               Nsim = Nsim, dgp = "Common stochastic volatility",
               stringsAsFactors = FALSE)
  }))
}

common_volatility_variance <- 0.5
common_volatility_lambda   <- exp(common_volatility_variance)
common_volatility_asymptotic <- 2 * pnorm(
  -qnorm(1 - alpha / 2) / sqrt(common_volatility_lambda))

set.seed(seeds[["volatility"]])
common_volatility_res <- simulate_common_volatility(
  Tmax, selected_T, Nsim_vol, alpha,
  volatility_variance = common_volatility_variance)
common_volatility_res$mcse <- mcse(common_volatility_res$reject,
                                   common_volatility_res$Nsim)

# =============================================================================
# 6. Extension 2: local-to-unity triangular array
#
# phi_T = 1 - c/T, so the DGP changes with T.  Each finite-T process is
# stationary, but the sequence approaches the unit-root boundary.  Note that
# the pre-sample value is drawn from the invariant distribution, i.e. this is
# the STATIONARY-START local-to-unity design (the limit is an Ornstein-
# Uhlenbeck process begun in its stationary distribution).  A zero-start design
# gives materially different finite-sample rejection frequencies; the
# initialisation is a modelling choice, not a technicality.
# =============================================================================

simulate_local_to_unity <- function(selected_T, Nsim, alpha, c_local = 5) {
  methods <- c("Conventional OLS", "HAC")
  records <- vector("list", length(selected_T))
  for (j in seq_along(selected_T)) {
    n   <- selected_T[j]
    phi <- 1 - c_local / n
    rej <- matrix(FALSE, nrow = Nsim, ncol = length(methods),
                  dimnames = list(NULL, methods))
    for (r in seq_len(Nsim)) {
      rej[r, ] <- slope_rejections(draw_ar1(n, phi), draw_ar1(n, phi),
                                   alpha)[methods]
    }
    records[[j]] <- data.frame(T = n, phi = phi, method = methods,
                               reject = colMeans(rej), Nsim = Nsim,
                               dgp = "Local-to-unity",
                               stringsAsFactors = FALSE)
  }
  do.call(rbind, records)
}

local_to_unity_c <- 5
set.seed(seeds[["local_unity"]])
local_to_unity_res <- simulate_local_to_unity(selected_T, Nsim_l2u, alpha,
                                              c_local = local_to_unity_c)
local_to_unity_res$mcse <- mcse(local_to_unity_res$reject, local_to_unity_res$Nsim)

# =============================================================================
# 7. Extension 3: distributed lags, Granger causality, omitted dynamics
#
# x and y are generated INDEPENDENTLY, so the population projection coefficients
# on the x lags are exactly zero in BOTH specifications -- including the one
# that omits y_{t-1}.  There is therefore no omitted-variable bias anywhere in
# this experiment; the entire distortion in the misspecified column is a
# failure of the conventional covariance estimator, which is precisely why HAC
# repairs most of it.
# =============================================================================

# Joint Wald test.  Returns NA (rather than failing) if the covariance matrix
# is numerically singular, which can happen for HAC at the smallest sample
# sizes; such replications are dropped from the corresponding average.
wald_reject <- function(b, V, alpha) {
  V <- (V + t(V)) / 2
  stat <- tryCatch(as.numeric(crossprod(b, solve(V, b))),
                   error = function(e) NA_real_)
  if (!is.finite(stat) || stat < 0) return(NA)
  stat > qchisq(1 - alpha, df = length(b))
}

simulate_granger <- function(sample_sizes, Nsim, alpha, phi_x = 0.8, phi_y = 0.8) {
  designs <- c("Correct dynamic model", "Omit lagged y")
  methods <- c("Conventional OLS", "HAC")
  records <- vector("list", length(sample_sizes))

  for (j in seq_along(sample_sizes)) {
    n <- sample_sizes[j]
    rej <- array(NA, dim = c(Nsim, length(designs), length(methods)),
                 dimnames = list(NULL, designs, methods))
    L <- hac_bandwidth(n)

    for (r in seq_len(Nsim)) {
      x <- draw_ar1(n + 2, phi_x)
      y <- draw_ar1(n + 2, phi_y)
      yv    <- y[3:(n + 2)]
      ylag  <- y[2:(n + 1)]
      xlag1 <- x[2:(n + 1)]
      xlag2 <- x[1:n]

      X_correct <- cbind(1, ylag, xlag1, xlag2)
      X_omit    <- cbind(1, xlag1, xlag2)
      colnames(X_correct) <- c("const", "ylag", "xlag1", "xlag2")
      colnames(X_omit)    <- c("const", "xlag1", "xlag2")
      designs_X <- list(`Correct dynamic model` = X_correct,
                        `Omit lagged y`         = X_omit)

      for (design in designs) {
        X <- designs_X[[design]]
        k <- ncol(X)
        XtXinv <- tryCatch(chol2inv(chol(crossprod(X))), error = function(e) NULL)
        if (is.null(XtXinv)) next
        bhat  <- as.vector(XtXinv %*% crossprod(X, yv))
        resid <- as.vector(yv - X %*% bhat)
        idx   <- match(c("xlag1", "xlag2"), colnames(X))

        # conventional (homoskedastic) covariance
        s2 <- sum(resid^2) / (n - k)
        Vc <- s2 * XtXinv
        rej[r, design, "Conventional OLS"] <-
          wald_reject(bhat[idx], Vc[idx, idx, drop = FALSE], alpha)

        # Bartlett HAC covariance, same estimator as everywhere else
        S  <- X * resid
        Vh <- n * XtXinv %*% hac_lrv_matrix(S, L, n / (n - k)) %*% XtXinv
        rej[r, design, "HAC"] <-
          wald_reject(bhat[idx], Vh[idx, idx, drop = FALSE], alpha)
      }
    }

    records[[j]] <- do.call(rbind, lapply(designs, function(design) {
      data.frame(T = n, specification = design, method = methods,
                 reject = as.numeric(colMeans(rej[, design, ], na.rm = TRUE)),
                 Nsim = Nsim,
                 test = "No Granger causality from x to y",
                 stringsAsFactors = FALSE)
    }))
  }
  do.call(rbind, records)
}

granger_sample_sizes <- c(100, 250, 500, 1000, 2000)
set.seed(seeds[["granger"]])
granger_res <- simulate_granger(granger_sample_sizes, Nsim_gr, alpha)
granger_res$mcse <- mcse(granger_res$reject, granger_res$Nsim)

# =============================================================================
# 8. Extension 4: local power and size-adjusted critical values
#
# Under the local alternative  y_t = (b / sqrt(T)) x_t + v_t  with x and v
# independent AR(1) processes, we compare conventional and HAC tests using
# SIZE-ADJUSTED critical values (the empirical 95th percentile of |t| under
# b = 0).  Size adjustment is what makes the comparison meaningful: an
# oversized test always has more raw power, so raw power curves would simply
# restate the size distortion.
#
# The size-adjusted conventional critical value is itself informative.  By
# Proposition 3.5 the conventional t-ratio has an N(0, lambda) limit, so its
# 95th percentile should converge to 1.96 * sqrt(lambda) -- a sharper check on
# the proposition than any tail rejection probability.
# =============================================================================

simulate_local_power <- function(sample_sizes, b_grid, Nsim, alpha,
                                 phi_x = 0.8, phi_v = 0.8) {
  methods <- c("Conventional OLS", "HAC")
  power_records <- vector("list", length(sample_sizes))
  cv_records    <- vector("list", length(sample_sizes))

  for (j in seq_along(sample_sizes)) {
    n <- sample_sizes[j]
    tstat <- array(NA_real_, dim = c(Nsim, length(b_grid), length(methods)),
                   dimnames = list(NULL, as.character(b_grid), methods))

    for (bi in seq_along(b_grid)) {
      bloc <- b_grid[bi]
      for (r in seq_len(Nsim)) {
        x <- draw_ar1(n, phi_x)
        v <- draw_ar1(n, phi_v)
        y <- (bloc / sqrt(n)) * x + v
        tstat[r, bi, ] <- slope_t_stats(x, y)[methods]
      }
    }

    null_index <- which(b_grid == 0)
    cv <- vapply(methods, function(m)
      unname(quantile(abs(tstat[, null_index, m]), 1 - alpha)), numeric(1))

    # Jarque-Bera test of normality on the null (b = 0) t-statistics: the
    # critical-value comparison above checks the SCALE of the limit
    # distribution (whether lambda is estimated correctly); this checks its
    # SHAPE, i.e. whether the limit is normal at all, as Proposition
    # \ref{prop:tstat} also claims.
    jb <- vapply(methods, function(m)
      jarque_bera(tstat[, null_index, m]), numeric(2))

    cv_records[[j]] <- data.frame(
      T = n, method = methods, critical_value = cv,
      nominal = qnorm(1 - alpha / 2),
      implied_sqrt_lambda = cv / qnorm(1 - alpha / 2),
      jb_statistic = jb["statistic", ],
      jb_pvalue    = jb["p_value", ],
      Nsim = Nsim, stringsAsFactors = FALSE
    )

    power_records[[j]] <- do.call(rbind, lapply(seq_along(b_grid), function(bi) {
      data.frame(
        T = n, b = b_grid[bi], method = methods,
        power = vapply(methods, function(m)
          mean(abs(tstat[, bi, m]) > cv[[m]]), numeric(1)),
        Nsim = Nsim, stringsAsFactors = FALSE
      )
    }))
  }

  list(power = do.call(rbind, power_records),
       critical_values = do.call(rbind, cv_records))
}

